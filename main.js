const applyLanguage = (language) => {
    const dictionary = translations[language] || translations.id;
    document.documentElement.lang = language;

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        element.textContent = dictionary[element.dataset.i18n];
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
        element.dataset.i18nAttr.split(',').forEach((pair) => {
            const [attribute, key] = pair.split(':');
            element.setAttribute(attribute.trim(), dictionary[key.trim()]);
        });
    });

    localStorage.setItem('portfolio-language', language);
    document.querySelector('[data-custom-select="language"] .custom-select-value').textContent = language.toUpperCase();
    document.querySelectorAll('[data-custom-select="language"] [role="option"]').forEach((option) => {
        option.setAttribute('aria-selected', String(option.dataset.value === language));
    });
};

const applyTheme = (theme) => {
    document.body.dataset.theme = theme;
    localStorage.setItem('portfolio-theme-v2', theme);
    const selectedOption = document.querySelector(`[data-custom-select="theme"] [data-value="${theme}"]`);
    document.querySelector('[data-custom-select="theme"] .custom-select-value').textContent = selectedOption.textContent;
    document.querySelectorAll('[data-custom-select="theme"] [role="option"]').forEach((option) => {
        option.setAttribute('aria-selected', String(option.dataset.value === theme));
    });
};

const savedLanguage = localStorage.getItem('portfolio-language') || 'id';
const availableThemes = ['baby-pink', 'black', 'white', 'baby-blue'];
const storedTheme = localStorage.getItem('portfolio-theme-v2');
const savedTheme = availableThemes.includes(storedTheme) ? storedTheme : 'baby-pink';

applyLanguage(savedLanguage);
applyTheme(savedTheme);

const closeCustomSelects = () => {
    document.querySelectorAll('.custom-select.is-open').forEach((select) => {
        select.classList.remove('is-open');
        select.querySelector('.select-trigger').setAttribute('aria-expanded', 'false');
    });
};

document.querySelectorAll('.custom-select').forEach((select) => {
    const trigger = select.querySelector('.select-trigger');
    const options = select.querySelectorAll('[role="option"]');

    trigger.addEventListener('click', () => {
        const isOpen = select.classList.contains('is-open');
        closeCustomSelects();
        if (!isOpen) {
            select.classList.add('is-open');
            trigger.setAttribute('aria-expanded', 'true');
        }
    });

    options.forEach((option) => {
        option.addEventListener('click', () => {
            options.forEach((item) => item.setAttribute('aria-selected', 'false'));
            option.setAttribute('aria-selected', 'true');
            if (select.dataset.customSelect === 'language') applyLanguage(option.dataset.value);
            if (select.dataset.customSelect === 'theme') applyTheme(option.dataset.value);
            closeCustomSelects();
        });
    });
});

document.addEventListener('click', (event) => {
    if (!event.target.closest('.custom-select')) closeCustomSelects();
});

