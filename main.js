document.querySelectorAll('.certificate-grid, .documentation-grid').forEach((gallery) => {
    gallery.scrollLeft = 0;
    let activePointer = null;
    let startX = 0;
    let startScrollLeft = 0;
    let wasDragged = false;

    gallery.addEventListener('pointerdown', (event) => {
        if (event.pointerType !== 'mouse' || event.button !== 0) return;
        activePointer = event.pointerId;
        startX = event.clientX;
        startScrollLeft = gallery.scrollLeft;
        wasDragged = false;
        gallery.classList.add('is-dragging');
        gallery.setPointerCapture(activePointer);
    });

    gallery.addEventListener('pointermove', (event) => {
        if (event.pointerId !== activePointer) return;
        const distance = event.clientX - startX;
        if (Math.abs(distance) > 5) wasDragged = true;
        if (wasDragged) gallery.scrollLeft = startScrollLeft - distance;
    });

    const stopDragging = (event) => {
        if (event.pointerId !== activePointer) return;
        activePointer = null;
        gallery.classList.remove('is-dragging');
        if (wasDragged) gallery.dataset.ignoreClick = 'true';
    };

    gallery.addEventListener('pointerup', stopDragging);
    gallery.addEventListener('pointercancel', stopDragging);
    gallery.addEventListener('click', (event) => {
        if (gallery.dataset.ignoreClick !== 'true') return;
        event.preventDefault();
        event.stopImmediatePropagation();
        delete gallery.dataset.ignoreClick;
    }, true);
});

const documentationGallery = document.querySelector('.documentation-grid');
if (documentationGallery) {
    const originalCards = [...documentationGallery.children];
    const firstClone = originalCards[0].cloneNode(true);
    const lastClone = originalCards[originalCards.length - 1].cloneNode(true);
    firstClone.dataset.loopClone = 'true';
    lastClone.dataset.loopClone = 'true';
    firstClone.setAttribute('aria-hidden', 'true');
    lastClone.setAttribute('aria-hidden', 'true');
    documentationGallery.prepend(lastClone);
    documentationGallery.append(firstClone);

    const cards = [...documentationGallery.children];
    const contentLeft = (card) => card.getBoundingClientRect().left
        - documentationGallery.getBoundingClientRect().left
        + documentationGallery.scrollLeft;
    const centerCard = (card, smooth = true) => {
        if (!smooth) documentationGallery.style.scrollBehavior = 'auto';
        documentationGallery.scrollTo({
            left: contentLeft(card) - (documentationGallery.clientWidth - card.offsetWidth) / 2,
            behavior: smooth ? 'smooth' : 'auto'
        });
        if (!smooth) requestAnimationFrame(() => { documentationGallery.style.scrollBehavior = ''; });
    };

    let settleTimer;
    let framePending = false;
    const getNearestCard = () => {
        const center = documentationGallery.scrollLeft + documentationGallery.clientWidth / 2;
        return cards.reduce((nearest, card) => {
            const distance = Math.abs(contentLeft(card) + card.offsetWidth / 2 - center);
            return !nearest || distance < nearest.distance ? { card, distance } : nearest;
        }, null).card;
    };
    const loopBackToRealPhoto = () => {
        const nearestCard = getNearestCard();
        if (nearestCard === lastClone) centerCard(originalCards[originalCards.length - 1], false);
        if (nearestCard === firstClone) centerCard(originalCards[0], false);
    };

    const updateSpotlight = () => {
        framePending = false;
        const nearestCard = getNearestCard();
        cards.forEach((card) => card.classList.toggle('is-spotlight', card === nearestCard));

        clearTimeout(settleTimer);
        if (!('onscrollend' in documentationGallery)) {
            settleTimer = setTimeout(loopBackToRealPhoto, 80);
        }
    };

    documentationGallery.addEventListener('scroll', () => {
        if (framePending) return;
        framePending = true;
        requestAnimationFrame(updateSpotlight);
    }, { passive: true });
    documentationGallery.addEventListener('scrollend', loopBackToRealPhoto);

    documentationGallery.addEventListener('keydown', (event) => {
        if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
        event.preventDefault();
        const direction = event.key === 'ArrowRight' ? 1 : -1;
        documentationGallery.scrollBy({ left: direction * (cards[0].offsetWidth + 18), behavior: 'smooth' });
    });

    requestAnimationFrame(() => {
        centerCard(originalCards[0], false);
        updateSpotlight();
    });
}

const revealItems = document.querySelectorAll(
    '.hero-copy, .hero-visual, .section, .section-heading, .card, .timeline-card, .organization-card, .project-card, .achievement-group, .contact-card'
);

if (window.matchMedia('(prefers-reduced-motion: reduce)').matches || !('IntersectionObserver' in window)) {
    revealItems.forEach((item) => item.classList.add('is-visible'));
} else {
    const motionTypes = ['bounce', 'merge', 'slide', 'roll'];
    let previousScrollY = window.scrollY;
    let scrollDirection = 'down';

    window.addEventListener('scroll', () => {
        const currentScrollY = window.scrollY;
        scrollDirection = currentScrollY < previousScrollY ? 'up' : 'down';
        previousScrollY = currentScrollY;
    }, { passive: true });

    revealItems.forEach((item, index) => {
        item.classList.add('reveal-on-scroll');
        item.dataset.motion = motionTypes[index % motionTypes.length];
        item.style.setProperty('--reveal-delay', `${(index % 3) * 90}ms`);
    });

    const revealObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            const item = entry.target;
            if (entry.isIntersecting) {
                if (scrollDirection === 'up') {
                    item.classList.add('is-visible', 'is-upward');
                } else {
                    item.classList.remove('is-visible', 'is-upward');
                    void item.offsetWidth;
                    item.classList.add('is-visible');
                }
                if (scrollDirection === 'down' && item.classList.contains('hero-copy')) {
                    const name = item.querySelector('.hero-name');
                    name.classList.remove('is-popping');
                    void name.offsetWidth;
                    name.classList.add('is-popping');
                }
            } else if (scrollDirection === 'down') {
                item.classList.remove('is-visible', 'is-upward');
                if (item.classList.contains('hero-copy')) item.querySelector('.hero-name').classList.remove('is-popping');
            }
        });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });

    revealItems.forEach((item) => revealObserver.observe(item));
}

const watchedSections = document.querySelectorAll('#tentang, #keahlian, #proyek, #kontak');
const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) return;

        document.querySelectorAll('[data-section-link]').forEach((link) => link.classList.remove('is-active'));
        document.querySelector(`[data-section-link="${entry.target.id}"]`)?.classList.add('is-active');
    });
}, { rootMargin: '-30% 0px -55% 0px', threshold: 0 });

watchedSections.forEach((section) => sectionObserver.observe(section));
